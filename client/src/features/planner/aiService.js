/**
 * aiService.js
 * Client-Side Bring-Your-Own-Key (BYOK) AI Assistant Service.
 *
 * PRIVACY GUARANTEE: The user's API key is stored exclusively in their
 * browser's localStorage and is NEVER sent or logged to the PackGo server.
 * Uses Google Gemini (Free tier) or Groq API directly from the browser.
 */
import axios from "axios";

const STORAGE_KEY = "packgo_byok_gemini_key";
const GEMINI_ENDPOINT =
  "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent";

export function getStoredAiKey() {
  return localStorage.getItem(STORAGE_KEY) || "";
}

export function saveStoredAiKey(key) {
  if (key && typeof key === "string") {
    localStorage.setItem(STORAGE_KEY, key.trim());
  } else {
    localStorage.removeItem(STORAGE_KEY);
  }
}

export function removeStoredAiKey() {
  localStorage.removeItem(STORAGE_KEY);
}

async function callGemini(apiKey, prompt) {
  if (!apiKey) {
    throw new Error("Missing Gemini API key.");
  }

  const res = await axios.post(
    `${GEMINI_ENDPOINT}?key=${apiKey}`,
    {
      contents: [
        {
          parts: [{ text: prompt }],
        },
      ],
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 300,
      },
    },
    {
      headers: { "Content-Type": "application/json" },
      timeout: 10000,
    },
  );

  const candidate = res.data?.candidates?.[0];
  const text = candidate?.content?.parts?.[0]?.text;
  if (!text) {
    throw new Error("No response generated by Gemini model.");
  }
  return text.trim();
}

/**
 * Generate a 2-sentence conversational narrative for a single day.
 */
export async function generateDaySummary({
  apiKey,
  destination,
  dayNumber,
  places = [],
}) {
  const stopNames = places.map((p) => p.name).join(", ");
  const prompt = `You are an expert local guide in ${destination}. Write a concise, charming 2-sentence summary introducing Day ${dayNumber} of an itinerary covering: ${stopNames}. Keep it warm, engaging, and practical. Do not use markdown headers.`;

  return await callGemini(apiKey, prompt);
}

/**
 * Generate a local insider tip for a specific place.
 */
export async function generateInsiderTip({
  apiKey,
  destination,
  placeName,
  category,
}) {
  const prompt = `Give 1 quick, practical insider tip for a visitor visiting "${placeName}" (${category}) in ${destination}. Mention the best timing, photography spot, dress advice, or local specialty. Keep it under 40 words.`;

  return await callGemini(apiKey, prompt);
}

/**
 * Generate 2 alternative stop recommendations to swap.
 */
export async function suggestPlaceSwap({
  apiKey,
  destination,
  currentPlace,
  interests = [],
}) {
  const prompt = `A traveler visiting ${destination} wants to swap out "${currentPlace.name}" (${currentPlace.category || "attraction"}).
Suggest 2 great alternative places in ${destination} matching interests: ${interests.join(", ") || "culture, sights"}.
Respond ONLY in valid JSON array format with 2 items, each having:
[
  { "name": "Place Name", "reason": "Why this is a great alternative", "estMinutes": 90 }
]`;

  const raw = await callGemini(apiKey, prompt);
  try {
    const jsonMatch = raw.match(/\[[\s\S]*\]/);
    if (jsonMatch) {
      return JSON.parse(jsonMatch[0]);
    }
    return JSON.parse(raw);
  } catch (_e) {
    return [
      {
        name: `Hidden Gem in ${destination}`,
        reason: raw.slice(0, 120),
        estMinutes: 90,
      },
    ];
  }
}
